const { chromium } = require('playwright');
const path = require('path'), fs = require('fs');
(async () => {
  const d3 = q => (new Date().getHours() >= 21) || q === 'R3,R2';
  const b = await chromium.launch();
  const pg = await (await b.newContext()).newPage();
  const errs = [];
  pg.on('pageerror', e => errs.push(e.message));
  const tmp = fs.mkdtempSync('/tmp/aos-');
  fs.copyFileSync(path.resolve(__dirname, '../index.html'), tmp + '/index.html');
  fs.writeFileSync(tmp + '/config.js', 'window.AOS_CONFIG={url:"",key:""};');
  await pg.goto('file://' + tmp + '/index.html'); await pg.waitForSelector('.chal'); await pg.evaluate(() => { S.chal = false; render() });
  await pg.waitForSelector('nav.tabs');
  const ok = (c, m) => { if (!c) { console.log('FAIL', m); process.exitCode = 1; } else console.log('ok  ', m); };
  const setup = () => pg.evaluate(() => { S.prospects = [{ id: 'A1', name: 'SPC Batiment', phone: '01 30 00 00 05', stage: 'a_contacter', city: 'Poissy' }]; S.calls = []; S.tab = 'appels'; S.call.pid = ''; render() });
  await setup();
  await pg.locator('[data-act=callstep][data-s=ans]').click();
  ok(await pg.locator('button[data-r="ans"]').count() === 1, 'bouton « A répondu, sans suite » présent');
  await pg.locator('button[data-act=callpanel][data-r="rap"]').click();
  ok(await pg.locator('#cd').inputValue() === '', 'date de rappel vide par défaut');
  await pg.locator('button[data-act=callres][data-r="rap"]').click();
  ok(await pg.evaluate(() => S.prospects[0].stage) === 'a_contacter', 'À rappeler sans date : refusé');
  await pg.locator('button[data-act=callpanel][data-r=""]').click();
  await pg.locator('button[data-r="ans"]').click();
  await pg.waitForTimeout(300);
  const r = await pg.evaluate(() => ({ st: S.prospects[0].stage, nd: S.prospects[0].nextDate, j: S.calls[0] && S.calls[0].joint, res: S.calls[0] && S.calls[0].result }));
  ok(r.st === 'contacte' && !!r.nd && r.j === true && r.res === 'ans', 'A répondu : contacté, relance datée, compte comme conversation ' + JSON.stringify(r));
  await setup();
  await pg.click('[data-act=numedit]');
  await pg.fill('#cphone', '06 12 34 56 78'); await pg.click('[data-act=numsave]'); await pg.waitForTimeout(400);
  ok(await pg.evaluate(() => S.prospects[0].phone) === '06 12 34 56 78', 'numéro modifiable depuis la fiche');
  // rappel à heure fixe : absent de la file avant l'heure, en tête à l'heure
  const q = await pg.evaluate(() => { const d = new Date(), pad = x => String(x).padStart(2, '0'), t = today();
    const later = pad((d.getHours() + 3) % 24) + ':00', soon = pad(d.getHours()) + ':' + pad(d.getMinutes());
    S.call.skip = []; S.prospects = [{ id: 'R1', name: 'Rappel 18h', phone: '01 30 00 00 11', stage: 'contacte', nextDate: t, nextTime: later }, { id: 'R2', name: 'Nouvelle', phone: '01 30 00 00 12', stage: 'a_contacter' }, { id: 'R3', name: 'Rappel maintenant', phone: '01 30 00 00 13', stage: 'contacte', nextDate: t, nextTime: soon }];
    return callQueue().map(p => p.id).join(',') });
  ok(d3(q), 'rappel à heure fixe : pas dans la file avant l\'heure, en tête à l\'heure ' + q);
  const fl = await pg.evaluate(() => { S.call.skip = []; S.prospects = [{ id: 'F1', name: 'Fixe 01', phone: '01 30 00 00 21', stage: 'a_contacter', score: 200 }, { id: 'M1', name: 'Mobile 06', phone: '06 12 00 00 22', stage: 'a_contacter', score: 10 }, { id: 'M7', name: 'Mobile 07', phone: '07 12 00 00 23', stage: 'a_contacter', score: 5 }, { id: 'F4', name: 'Fixe 04', phone: '04 30 00 00 24', stage: 'a_contacter', score: 1 }];
    const r = {}; for (const m of ['all', 'm06', 'p01', 'mobile', 'fixe']) { S.call.mob = m; r[m] = callQueue().map(p => p.id).join(',') } S.call.mob = 'all'; return r });
  ok(fl.all.startsWith('M1,M7') && fl.m06 === 'M1' && fl.p01 === 'F1' && fl.mobile === 'M1,M7' && fl.fixe === 'F1,F4', 'filtres 06 / 01 / mobiles / fixes et mobiles en priorité ' + JSON.stringify(fl));
  ok(errs.length === 0, 'aucune erreur JS ' + errs.join('|'));
  await b.close();
})();
