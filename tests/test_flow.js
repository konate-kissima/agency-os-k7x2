const { chromium } = require('playwright');
const path = require('path'), fs = require('fs');
(async () => {
  const b = await chromium.launch(); const pg = await (await b.newContext()).newPage();
  const errs = []; pg.on('pageerror', e => errs.push(e.message));
  const tmp = fs.mkdtempSync('/tmp/aos-'); fs.copyFileSync(path.resolve(__dirname, '../index.html'), tmp + '/index.html');
  fs.writeFileSync(tmp + '/config.js', 'window.AOS_CONFIG={url:"",key:""};');
  await pg.goto('file://' + tmp + '/index.html'); await pg.waitForSelector('.chal'); await pg.evaluate(() => { S.chal = false; render() });
  const ok = (c, m) => { if (!c) { console.log('FAIL', m); process.exitCode = 1 } else console.log('ok  ', m) };
  const seed = async (id, name, ph) => pg.evaluate(async ([id, name, ph]) => { const d = { name, stage: 'a_contacter', phone: ph, score: 99 }; S.prospects.length = 0; S.calls.length = 0; S.prospects.push({ id, ...d }); await DB.set('prospects', id, d); S.call.pid = ''; S.call.panel = ''; S.tab = 'appels'; render() }, [id, name, ph]);
  await seed('f1', 'Flux Un', '0612345601'); await pg.waitForTimeout(200);
  ok(await pg.$('.cres [data-r="rdvv"]') !== null && await pg.$('.cres [data-r="no"]') !== null, 'tous les résultats visibles sans passer par « Répondu »');
  await pg.click('.cres [data-r="no"]');
  ok((await pg.$$('[data-act="objpick"]')).length >= 9, 'objections en boutons');
  await pg.click('[data-act="objpick"][data-o="Pas le temps"]'); await pg.waitForTimeout(700);
  const r1 = await pg.evaluate(() => ({ st: byId('f1').stage, obj: (S.calls.find(c => c.prospectId === 'f1') || {}).obj, res: (S.calls.find(c => c.prospectId === 'f1') || {}).result }));
  ok(r1.st === 'perdu' && r1.obj === 'Pas le temps' && r1.res === 'no', 'un clic sur une objection enregistre le résultat ' + JSON.stringify(r1));
  await seed('f2', 'Flux Deux', '0612345602'); await pg.waitForTimeout(200);
  await pg.keyboard.press('4'); ok(await pg.$('[data-act="rapquick"]') !== null, 'touche 4 : panneau « à rappeler »');
  await pg.keyboard.press('2'); await pg.waitForTimeout(700);
  const r2 = await pg.evaluate(() => ({ st: byId('f2').stage, nd: byId('f2').nextDate, nt: byId('f2').nextTime, exp: workday(3) }));
  ok(r2.st === 'contacte' && r2.nd === r2.exp && r2.nt === '', 'touche 2 : rappel dans 3 jours, sans heure ' + JSON.stringify(r2));
  await seed('f3', 'Flux Trois', '0612345603'); await pg.waitForTimeout(200);
  await pg.keyboard.press('6'); await pg.keyboard.press('1'); await pg.waitForTimeout(700);
  ok(await pg.evaluate(() => byId('f3').stage === 'perdu'), 'touches 6 puis 1 : pas intéressé + objection');
  await pg.click('#geneb'); await pg.fill('#genet', 'test remarque'); await pg.click('#genes'); await pg.waitForTimeout(300);
  ok(await pg.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('aos:settings') || '{}')).some(k => k.startsWith('gene_'))), 'bouton « Ça me gêne » enregistre la remarque');
  await pg.evaluate(() => { S.tab = 'stats'; render() }); ok((await pg.innerText('body')).includes('Temps mort'), 'stats : temps mort');
  ok(errs.length === 0, 'aucune erreur JS ' + errs.join('|'));
  await b.close();
})();
