const { chromium } = require('playwright');
const path = require('path'), fs = require('fs');
(async () => {
  const b = await chromium.launch();
  const pg = await (await b.newContext()).newPage();
  const errs = [];
  pg.on('pageerror', e => errs.push('pageerror: ' + e.message));
  const tmp = fs.mkdtempSync('/tmp/aos-');
  fs.copyFileSync(path.resolve(__dirname, '../index.html'), tmp + '/index.html');
  fs.writeFileSync(tmp + '/config.js', 'window.AOS_CONFIG={url:"",key:""};');
  await pg.goto('file://' + tmp + '/index.html'); await pg.waitForSelector('.chal'); await pg.evaluate(() => { S.chal = false; render() });
  await pg.waitForSelector('nav.tabs');
  const ok = (c, m) => { if (!c) { console.log('FAIL', m); process.exitCode = 1; } else console.log('ok  ', m); };
  await pg.evaluate(() => { S.prospects = [{ id: 'R1', name: 'Plomberie Test', phone: '01 30 00 00 01', stage: 'rdv', city: 'Poissy' }]; openProspect('R1') });
  const t = await pg.locator('#dlg').innerText();
  ok(t.includes('Préparer le rendez-vous'), 'fiche RDV : bloc « Préparer le rendez-vous »');
  const inner = await pg.locator('#dlg .script').textContent();
  ok(inner.includes('3000') && !inner.includes('{prix_pilote}'), 'prix pilote injecté');
  ok(inner.includes('DÉCOUVERTE') && inner.includes('MON OFFRE'), 'trame + offre présentes');
  await pg.evaluate(() => { document.getElementById('dlg').close(); S.tab = 'scripts'; render() });
  ok(await pg.locator('#s-rdv').count() === 1 && await pg.locator('#s-offer').count() === 1, 'onglet Scripts : trame RDV et offre éditables');
  ok(await pg.evaluate(() => Object.keys(settings().scripts).includes('D') && settings().scripts.H.name.includes('tel quel')), 'angle D ajouté, script H intact');
  await pg.evaluate(() => { document.getElementById('s-offer').value = 'OFFRE TEST'; });
  await pg.evaluate(async () => { await saveSettings() });
  ok(await pg.evaluate(() => S.settings.offerText === 'OFFRE TEST'), 'offre enregistrée');
  ok(await pg.evaluate(() => OBJ.some(o => o.includes('Signal chaud'))), 'signal chaud dans la liste des objections');
  ok(errs.length === 0, 'aucune erreur JS ' + errs.join('|'));
  await b.close();
})();
